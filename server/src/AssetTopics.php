    /** 그 카테고리의 주제 목록 [key => label]. 없으면 빈 배열. */
    public static function of(string $category): array
    {
        $out = [];
        foreach (self::MAP[$category] ?? [] as $k => $v) $out[$k] = $v[0];
        return $out;
    }

    /** 주제의 매칭 낱말들. */
    public static function terms(string $category, string $topic): array
    {
        return self::MAP[$category][$topic][1] ?? [];
    }

    public static function exists(string $category, string $topic): bool
    {
        return isset(self::MAP[$category][$topic]);
    }

    public static function all(): array
    {
        $out = [];
        foreach (self::MAP as $cat => $topics) $out[$cat] = self::of($cat);
        return $out;
    }

    /**
     * 주제 조건 SQL 한 조각을 만든다. 반환 [sql, params].
     * '@page:x' / '@kind:x' 는 장표 전용(컬럼 비교), 그 외는 태그 부분일치.
     */
    public static function clause(string $category, string $topic, string $pfx = ':tp'): array
    {
        $terms = self::terms($category, $topic);
        if (!$terms) return ['', []];
        $or = []; $params = []; $i = 0;
        foreach ($terms as $t) {
            if (str_starts_with($t, '@page:')) {
                $or[] = "a.slide_page = {$pfx}p{$i}";
                $params["{$pfx}p{$i}"] = substr($t, 6);
            } elseif (str_starts_with($t, '@kind:')) {
                $or[] = "a.slide_kind = {$pfx}k{$i}";
                $params["{$pfx}k{$i}"] = substr($t, 6);
            } elseif (str_starts_with($t, '@nameend:')) {
                $or[] = "COALESCE(a.name,'') LIKE {$pfx}e{$i}";     // 이름이 그 글자로 끝남(…부/…청)
                $params["{$pfx}e{$i}"] = '%' . substr($t, 9);
            } elseif (str_starts_with($t, '@name:')) {
                $or[] = "COALESCE(a.name,'') LIKE {$pfx}n{$i}";
                $params["{$pfx}n{$i}"] = '%' . substr($t, 6) . '%';
            } else {
                $or[] = "COALESCE(a.tags,'') LIKE {$pfx}t{$i}";
                $params["{$pfx}t{$i}"] = '%' . $t . '%';
            }
            $i++;
        }
        return ['(' . implode(' OR ', $or) . ')', $params];
    }
